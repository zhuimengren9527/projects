from collections import Counter


def minWindow(s: str, t: str) -> str:
    # 🛡️ 工业级前置鲁棒性检查：如果原串为空，或者通缉令为空，或者原串比通缉令还短，直接无脑返回空
    if not s or not t or len(s) < len(t):
        return ""
    # =====================================================================
    # 🕵️‍♂️ 第一阶段：初始化通缉令与捕鱼口袋
    # =====================================================================
    need = Counter(t)  # 刚性负债账本：记录 t 里面每个嫌疑人需要的数量
    window = Counter()  # 动态窗口口袋：记录当前抓捕范围内手里的存货

    left, right = 0, 0
    valid = 0  # 核心指标：记录有多少种字符的频次已经精准达标

    # 结算记录：用来记住历史上最短的那个合格片段的起始点和长度
    start = 0
    min_len = float("inf")  # 初始设为无穷大，方便被后面的更小值无情刷新

    # =====================================================================
    # 🎬 第二阶段：探长（right）野蛮扩张，疯狂扩窗吃人
    # =====================================================================
    while right < len(s):
        c = s[right]  # 探长即将吃进嘴里的新字符
        right += 1  # 🌟 刚性动作：探长向前迈出一步，右边界右移

        # 【填空 1：吃人对账】
        if c in need:
            window[c] += 1  # 货进袋子
            # 🌟 刚好达标那一瞬间的雪中送炭：
            if window[c] == need[c]:
                valid += 1  # 拿下一种嫌疑人的核心指标

        # =====================================================================
        # 🎬 第三阶段：后勤（left）无情裁剪，逼出破产临界点
        # =====================================================================
        # 当有效指标 valid 刚好等于通缉令的种类总数时，说明人头全齐了，警报拉响！
        while valid == len(need):

            # 🌟 【填空 4：记录战报】
            # 既然人头全齐了，立刻看看当前的捕鱼范围 (right - left) 是不是比历史记录还要短
            if right - left < min_len:
                start = left  # 记录这发最优解的起始坐标
                min_len = right - left  # 刷新历史最短长度记录

            d = s[left]  # 后勤队长准备从左边物理开除的老员工
            left += 1  # 🌟 刚性动作：后勤向前迈出一步，左边界右移

            # 【填空 3：踢人扣账 - 与吃人完全对称】
            if d in need:
                # 🌟 刚好踩在达标线上的临界点：再踢这个人，他的数量就要低于通缉令了！
                if window[d] == need[d]:
                    valid -= 1  # 大盘立刻降级，指标破产
                window[d] -= 1  # 货出袋子

    # =====================================================================
    # 🏁 第四阶段：最终结算防线（三元运算符）
    # =====================================================================
    # 如果 min_len 依然是无穷大，说明从头到尾连一次全齐的机会都没有，返回空字符串
    # 否则，利用 Python 字符串切片算子，从大流水 s 中把最优抓捕片段割下来放行
    return "" if min_len == float("inf") else s[start : start + min_len]